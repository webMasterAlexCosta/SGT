const { baseFrontend } = require('./contexto-fixture.cjs');
const fs = require('node:fs');
const path = require('node:path');
const { execute } = require('./ambiente-real.cjs');
execute('historico-nome', async ({ page, context, account, fixture, check, screenshot, open, confirmPassword, recordBusiness, report }) => {
  const business = JSON.parse(fs.readFileSync(path.join(process.env.SGT_TEST_RUNTIME, 'private/e2e-business.json')));
  const base = baseFrontend();
  await open('/historico');
  const personBefore = (await (await context.request.get(base + `/api/pessoas/${business.pessoaId}`)).json()).data;
  const events = (await (await context.request.get(base + `/api/vinculos-contratuais/${business.vinculoId}/eventos`)).json()).data;
  const origin = events.find(e => e.tipo === 'CRIACAO');
  check('Origem nominal consultada no Java', !!origin?.id);
  await page.getByRole('tab', { name: 'Nome', exact: true }).click();
  const query = page.getByRole('form', { name: 'Consulta histórica' });
  await query.getByLabel('ID da pessoa', { exact: true }).fill(String(business.pessoaId));
  await query.getByLabel('ID do vínculo', { exact: true }).fill(String(business.vinculoId));
  await query.getByLabel('Data efetiva consultada', { exact: true }).fill(fixture.dates.today);
  const before = new Date().toISOString();
  await query.getByLabel('Conhecido até (ISO com fuso)', { exact: true }).fill(before);
  await query.getByRole('button', { name: 'Consultar histórico', exact: true }).click();
  await page.locator('summary').filter({ hasText: 'Incorporar uma fonte histórica' }).click();
  const form = page.getByRole('form', { name: 'Fonte histórica' });
  await form.getByRole('button', { name: 'Carregar versões atuais', exact: true }).click();
  for (const label of ['Versão esperada da pessoa', 'Versão esperada do vínculo']) {
    const id = await form.getByLabel(label, { exact: true }).getAttribute('id');
    await page.waitForFunction(id => document.getElementById(id)?.value !== '', id);
  }
  const name = 'PESSOA SINTETICA — NOME HISTORICO COMPROVADO';
  await form.getByLabel('Nome comprovado', { exact: true }).fill(name);
  await form.getByLabel('Início do intervalo comprovado', { exact: true }).fill(fixture.dates.today);
  await form.getByLabel('Referência SEI', { exact: true }).fill('SINTETICO-E2E-NOME-20261101');
  await form.getByLabel('ID do evento nominal retificado', { exact: true }).fill(String(origin.id));
  await form.getByLabel('Motivo / justificativa', { exact: true }).fill('Correção documental sintética da fotografia nominal; mesma Pessoa e mesmo Vínculo.');
  await form.getByLabel('Autorização', { exact: true }).fill('SINTETICO-E2E-CONCESSAO-VIGENTE');
  await form.getByRole('button', { name: 'Gerar prévia', exact: true }).click();
  await form.getByRole('heading', { name: 'Impactos informados pelo servidor' }).waitFor();
  await form.getByLabel('Li os impactos e confirmo esta intenção.', { exact: true }).check();
  await screenshot('previa');
  const endpoint = `/api/pessoas/${business.pessoaId}/provas-nome`;
  const confirmed = page.waitForResponse(r => new URL(r.url()).pathname === endpoint && r.request().method() === 'POST' && r.status() === 201, { timeout: 20000 });
  await form.getByRole('button', { name: 'Confirmar incorporação', exact: true }).click();
  await confirmPassword();
  const response = await confirmed;
  const receipt = (await response.json()).data;
  const payload = response.request().postDataJSON();
  recordBusiness({ nomeProvaId: receipt.id, nomeReplay: payload, nomeEndpoint: endpoint, nomeConhecidoAntes: before, nomeHistoricoComprovado: name, nomeAtualAnterior: personBefore.nome });
  check('Prova preserva a mesma Pessoa e o mesmo Vínculo', receipt.pessoaId === business.pessoaId && receipt.vinculoId === business.vinculoId, { id: receipt.id, pessoaId: receipt.pessoaId, vinculoId: receipt.vinculoId });
  const csrf = (await (await context.request.get(base + '/api/autenticacao/csrf')).json()).data;
  const replay = await context.request.post(base + endpoint, { data: payload, headers: { [csrf.headerName]: csrf.token, 'X-User-Password': account.password, Origin: base } });
  const again = (await replay.json()).data;
  report.http.push({ method: 'POST', path: endpoint, status: replay.status(), driver: 'APIRequestContext — reenvio do comando capturado no React' });
  check('Reenvio nominal é idempotente', replay.ok() && again.reenvio === true && again.id === receipt.id);
  const route = `/api/pessoas/${business.pessoaId}/nome-historico`;
  const params = { vinculoId: business.vinculoId, data: fixture.dates.today };
  const previous = (await (await context.request.get(base + route, { params: { ...params, conhecidoAte: before } })).json()).data;
  const current = (await (await context.request.get(base + route, { params })).json()).data;
  const personAfter = (await (await context.request.get(base + `/api/pessoas/${business.pessoaId}`)).json()).data;
  check('Corte anterior preserva a fotografia nominal anterior', previous.nome === personBefore.nome && previous.comprovado === true);
  check('Conhecimento atual resolve o nome comprovado', current.nome === name && current.comprovado === true);
  check('Prova histórica não sobrescreve cadastro atual da Pessoa', personAfter.nome === personBefore.nome);
  await screenshot('registrado');
});
