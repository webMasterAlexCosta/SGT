// Um rascunho por lote. Preparação causal para retenção de POST/PUT em duas abas.
const fs = require('node:fs');
const path = require('node:path');
const { baseFrontend } = require('./contexto-fixture.cjs');
const { execute } = require('./ambiente-real.cjs');
const phase = process.env.SGT_RI03_PHASE;
if (!['post','put'].includes(phase)) throw new Error('Defina SGT_RI03_PHASE post ou put.');
const caseLabel = process.env.SGT_RI03_CASE;
if (!/^\d{2}$/.test(caseLabel || '')) throw new Error('Defina SGT_RI03_CASE com dois dígitos.');
const field = phase === 'post' ? 'ri03ContratoPostId' : 'ri03ContratoPutId';

execute('preparacao-ri03-real-' + phase, async ({ page, context, fixture, report, check, open, confirmPassword, recordBusiness, screenshot }) => {
  const business = JSON.parse(fs.readFileSync(path.join(process.env.SGT_TEST_RUNTIME, 'private/e2e-business.json')));
  check('Rascunho desta fase não deve ser criado novamente', !business[field]);
  const digit = digits => {
    const weights = digits.length === 12 ? [5,4,3,2,9,8,7,6,5,4,3,2] : [6,5,4,3,2,9,8,7,6,5,4,3,2];
    const rest = [...digits].reduce((sum,n,index) => sum + Number(n) * weights[index], 0) % 11;
    return rest < 2 ? '0' : String(11 - rest);
  };
  let cnpj = '739999' + caseLabel + '0001'; cnpj += digit(cnpj); cnpj += digit(cnpj);
  const name = 'SINTETICA-E2E-RI03-FINAL02-CASO-' + caseLabel;
  const number = 'SINTETICO-RI03-' + phase.toUpperCase() + '-FINAL02-' + caseLabel;
  const base = baseFrontend();
  await open('/contratos');
  const providersResponse = await context.request.get(base + '/api/fornecedores');
  const providers = (await providersResponse.json()).data;
  check('Empresa-alvo ainda não existe na preparação', providersResponse.status() === 200 && providers.every(item => item.cnpj !== cnpj));
  const listResponse = await context.request.get(base + '/api/contratos');
  const list = (await listResponse.json()).data;
  check('Intenção contratual não existe antes do POST', listResponse.status() === 200 && list.every(item => item.numeroContrato !== number));
  await page.getByRole('button', { name: 'Novo contrato', exact: true }).click();
  const form = page.getByRole('dialog', { name: 'Novo rascunho', exact: true });
  await form.getByLabel('Número do contrato', { exact: true }).fill(number);
  await form.getByLabel('Ano', { exact: true }).fill(fixture.dates.today.slice(0,4));
  await form.getByRole('combobox', { name: 'Tipo de contratação', exact: true }).selectOption(String(fixture.ids.tipo));
  await form.getByLabel('Efetivo total previsto', { exact: true }).fill('100');
  await form.getByRole('textbox', { name: /^Descrição/ }).fill('SINTETICO E2E RI03: rascunho exclusivo para comprovar fronteira de sessão e recuperação legítima.');
  await form.getByLabel('CNPJ da empresa', { exact: true }).fill(cnpj);
  await form.getByLabel('Razão social', { exact: true }).fill(name);
  await form.getByLabel('Nome fantasia', { exact: true }).fill('SINTETICO RI03 FINAL02');
  await form.getByLabel('Data de início', { exact: true }).fill(fixture.dates.today);
  await form.getByLabel('Data de término', { exact: true }).fill(fixture.objects.contrato_rascunho.dataFim);
  const pending = page.waitForResponse(r => new URL(r.url()).pathname === '/api/contratos' && r.request().method() === 'POST');
  pending.catch(() => {});
  await form.getByRole('button', { name: 'Criar rascunho', exact: true }).click();
  await confirmPassword();
  const response = await pending;
  const envelope = await response.json();
  check('Rascunho criado pela UI e senha com Java201', response.status() === 201, { status: response.status(), code: envelope.code });
  const created = envelope.data;
  recordBusiness({ [field]: created.id, [field + 'Numero']: number, ri03FornecedorCnpj: cnpj, ri03FornecedorNome: name, ri03Case: caseLabel });
  check('Rascunho não publicado, mesma Gestão, capacidade100 e sem fornecedor', created.id > 0 && created.estadoNegocial === 'RASCUNHO' && created.gestaoLocalId === fixture.ids.gestao_origem && created.efetivoPrevisto === 100 && created.fornecedorId == null && created.cnpjEmpresa === cnpj);
  const persistedResponse = await context.request.get(base + '/api/contratos/' + created.id);
  const persisted = (await persistedResponse.json()).data;
  check('GET independente confirma a mesma pré-condição sem associação', persistedResponse.status() === 200 && persisted.id === created.id && persisted.fornecedorId == null && persisted.estadoNegocial === 'RASCUNHO');
  await page.getByLabel('Senha de Acesso', { exact: true }).waitFor({ state: 'hidden' });
  await form.waitFor({ state: 'hidden' });
  report.scope = 'PREPARATION_ONLY_NOT_ACCEPTANCE';
  report.prepared = { phase, contractId: created.id, supplierAbsent: true, supplierId: null, capacity: 100 };
  await screenshot('rascunho-causal');
});
