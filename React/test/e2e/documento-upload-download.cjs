const { contratoDaFixture } = require('./contexto-fixture.cjs');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execute } = require('./ambiente-real.cjs');
execute('documento-upload-download', async ({ page, fixture, check, screenshot, open, confirmPassword, recordBusiness }) => {
  const contratoAlvo = contratoDaFixture(fixture);
  await open('/contratos');
  await page.getByRole('button', { name: contratoAlvo.botaoAbrir, exact: true }).click();
  const detail = page.getByRole('dialog', { name: contratoAlvo.titulo, exact: true });
  await detail.waitFor();
  const form = detail.locator('form').filter({ has: page.getByRole('heading', { name: 'Registrar documento', exact: true }) });
  await form.getByLabel(/^Título/).fill('DOCUMENTO SINTETICO E2E — sem valor administrativo');
  await form.getByLabel(/^Data efetiva/).fill(fixture.dates.today);
  await form.getByLabel(/^Referência SEI/).fill('SINTETICO-E2E-DOCUMENTO-20261101');
  const source = fs.readFileSync(path.resolve(__dirname, '../../src/assets/logo-footer.png'));
  await form.getByLabel(/^Arquivo opcional/).setInputFiles({ name: 'comprovante-sintetico.png', mimeType: 'image/png', buffer: source });
  const created = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === `${contratoAlvo.api}/documentos` && r.status() === 201, { timeout: 20000 });
  await form.getByRole('button', { name: /Registrar com confirmação/i }).click();
  await confirmPassword();
  const response = await created;
  const body = await response.json();
  recordBusiness({ documentoId: body.data.id });
  check('Documento recebido e persistido pelo Java', !!body.data.id, { status: response.status(), documentoId: body.data.id });
  const item = detail.locator('article').filter({ hasText: 'DOCUMENTO SINTETICO E2E — sem valor administrativo' }).first();
  await item.waitFor();
  const downloadPromise = page.waitForEvent('download', { timeout: 15000 });
  await item.getByRole('button', { name: 'Baixar', exact: true }).click();
  const download = await downloadPromise;
  const downloaded = fs.readFileSync(await download.path());
  const digest = value => crypto.createHash('sha256').update(value).digest('hex');
  check('Download autenticado preserva exatamente os bytes enviados', digest(source) === digest(downloaded), { sha256: digest(downloaded), bytes: downloaded.length, filename: download.suggestedFilename() });
  await screenshot('documento-registrado');
});
