const { baseFrontend, contratoDaFixture } = require('./contexto-fixture.cjs');
const { execute } = require('./ambiente-real.cjs');
execute('correcao-cnpj', async ({ page, context, fixture, account, report, check, open, screenshot, confirmPassword, recordBusiness }) => {
  const contratoAlvo = contratoDaFixture(fixture);
  const base = baseFrontend();
  await open('/contratos');
  const before = (await (await context.request.get(base + `${contratoAlvo.api}`)).json()).data;
  const date = new Date(fixture.dates.today + 'T12:00:00Z'); date.setUTCDate(date.getUTCDate() + 1);
  const effective = date.toISOString().slice(0, 10);
  const corrected = '11222333000181';
  await page.getByRole('button', { name: contratoAlvo.botaoAbrir, exact: true }).click();
  const detail = page.getByRole('dialog', { name: contratoAlvo.titulo, exact: true });
  await detail.getByRole('tab', { name: 'Correções CNPJ', exact: true }).click();
  const form = detail.getByRole('form', { name: 'Correção material de CNPJ', exact: true });
  await form.getByLabel(/CNPJ corrigido/).fill(corrected);
  await form.getByLabel(/Data efetiva da correção/).fill(effective);
  await form.getByLabel(/Data do ato da correção/).fill(fixture.dates.today);
  await form.getByLabel(/Referência SEI da correção/).fill('SINTETICO-E2E-CNPJ-CORRECAO');
  await form.getByLabel(/Motivo da correção/).fill('SINTETICO E2E — erro material no identificador, sem mudança da empresa, fonte sem validade administrativa real.');
  check('Correção material usa comando próprio sem prévia inexistente', await form.getByRole('button', { name: /prévia/i }).count() === 0);
  const endpoint = `${contratoAlvo.api}/correcoes-cnpj`;
  const confirmed = page.waitForResponse(r => new URL(r.url()).pathname === endpoint && r.request().method() === 'POST');
  await form.getByRole('button', { name: 'Corrigir CNPJ com confirmação', exact: true }).click();
  await confirmPassword();
  const response = await confirmed;
  const envelope = await response.json();
  check('Correção real registrada com confirmação de senha', response.status() === 201, { status: response.status(), message: envelope.message });
  const receipt = envelope.data;
  const payload = response.request().postDataJSON();
  check('Recibo registra CNPJ anterior, corrigido e alcance', receipt.cnpjAnterior === before.cnpjEmpresa && receipt.cnpjCorrigido === corrected && receipt.dataEfetiva === effective);
  await detail.getByText('Correção de CNPJ registrada.', { exact: true }).waitFor();
  const current = (await (await context.request.get(base + `${contratoAlvo.api}`)).json()).data;
  const future = (await (await context.request.get(base + `${contratoAlvo.api}/posicao-temporal`, { params: { data: effective } })).json()).data;
  check('Projeção corrente respeita a data efetiva futura', current.cnpjEmpresa === before.cnpjEmpresa && future.versaoContratual.cnpjEmpresa === corrected);
  check('Razão social e identidade da empresa não são trocadas pelo React', current.razaoSocialEmpresa === before.razaoSocialEmpresa && current.fornecedorId === before.fornecedorId);
  const csrf = (await (await context.request.get(base + '/api/autenticacao/csrf')).json()).data;
  const replay = await context.request.post(base + endpoint, { data: payload, headers: { [csrf.headerName]: csrf.token, 'X-User-Password': account.password, Origin: base } });
  check('Reenvio idempotente mantém a mesma correção', replay.status() === 201 && (await replay.json()).data.id === receipt.id);
  recordBusiness({ cnpjCorrecaoId: receipt.id, cnpjReplay: payload, cnpjEndpoint: endpoint, cnpjDataEfetiva: effective, cnpjCorrigido: corrected });
  report.http.push({ method: 'POST', path: endpoint, status: replay.status(), driver: 'APIRequestContext — reenvio da intenção capturada no React' });
  await screenshot('correcao-persistida');
});
