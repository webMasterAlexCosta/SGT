const { baseFrontend, contratoDaFixture } = require('./contexto-fixture.cjs');
const crypto = require('node:crypto');
const { runtimeObservado } = require('./runtime-observado.cjs');
const runtimeObservation = runtimeObservado();
const { execute } = require('./ambiente-real.cjs');
execute('seguranca-concorrencia', async ({ page, context, account, fixture, check, open, recordBusiness, report }) => {
  const contratoAlvo = contratoDaFixture(fixture);
  report.runtimeObservation = runtimeObservation;
  await open('/historico');
  const base = baseFrontend();
  const endpoint = `/api/catalogos-temporais/MOTIVO_DESLIGAMENTO/${fixture.ids.motivo_desligamento}/transicoes`;
  const itemUrl = `/api/motivos-desligamento/${fixture.ids.motivo_desligamento}`;
  const read = async route => (await (await context.request.get(base + route)).json()).data;
  const csrf = await read('/api/autenticacao/csrf');
  const headers = { [csrf.headerName]: csrf.token, 'X-User-Password': account.password, Origin: base };
  const actual = await read(itemUrl);
  const intent = suffix => ({ dataEfetiva: fixture.dates.today, ativo: !actual.ativo, motivo: `SINTETICO E2E — concorrência real ${suffix}`, evidencia: 'SINTETICO-E2E-CONCORRENCIA, sem valor administrativo.', autorizacao: 'SINTETICO-E2E-GESTOR-LOCAL', versaoEsperada: actual.version, chaveIdempotencia: crypto.randomUUID() });
  const candidate = intent('controle');
  const anonymous = await context.browser().newContext();
  const unauthenticated = await anonymous.request.get(base + `${contratoAlvo.api}`);
  check('Servidor exige sessão real na leitura de contratos', unauthenticated.status() === 401);
  await anonymous.close();
  const noCsrf = await context.request.post(base + endpoint + '/previa', { data: candidate, headers: { Origin: base } });
  check('Mutação sem cabeçalho CSRF é recusada', noCsrf.status() === 403);
  const badOrigin = await context.request.post(base + endpoint + '/previa', { data: candidate, headers: { ...headers, Origin: 'https://origem-sintetica-nao-autorizada.invalid' } });
  check('Origem não autorizada é recusada pelo Java', badOrigin.status() === 403);
  const preview = await context.request.post(base + endpoint + '/previa', { data: candidate, headers });
  check('Sessão e CSRF corretos geram prévia', preview.status() === 200);
  const candidateReady = { ...candidate, confirmarImpacto: true, tokenPrevia: (await preview.json()).data.tokenPrevia };
  const wrongPassword = await context.request.post(base + endpoint, { data: candidateReady, headers: { ...headers, 'X-User-Password': 'SINTETICO-SENHA-DELIBERADAMENTE-INCORRETA' } });
  const passwordError = await wrongPassword.json();
  check('Confirmação com senha incorreta é recusada sem persistência', wrongPassword.status() === 403 && passwordError.code === 'INVALID_CONFIRMATION_PASSWORD');
  check('Negativas não consumiram versão do catálogo', (await read(itemUrl)).version === actual.version);
  const commands = [];
  for (const suffix of ['A', 'B']) {
    const data = intent(suffix);
    const response = await context.request.post(base + endpoint + '/previa', { data, headers });
    check(`Prévia concorrente ${suffix} válida na mesma versão`, response.status() === 200);
    commands.push({ ...data, confirmarImpacto: true, tokenPrevia: (await response.json()).data.tokenPrevia });
  }
  const beforeConcurrent = new Date().toISOString();
  const results = await Promise.all(commands.map(async (data, index) => {
    const started = Date.now();
    const response = await context.request.post(base + endpoint, { data, headers });
    const finished = Date.now();
    return { index, started, finished, status: response.status(), body: await response.json() };
  }));
  report.concurrent = results.map(({ index, started, finished, status }) => ({ index, started, finished, status }));
  check('Duas requisições reais ficaram em voo simultaneamente', Math.max(...results.map(r => r.started)) < Math.min(...results.map(r => r.finished)));
  check('Concorrência na mesma versão produz um sucesso e um conflito', results.map(r => r.status).sort().join(',') === '200,409', { statuses: results.map(r => r.status) });
  const success = results.find(r => r.status === 200);
  const rejected = results.find(r => r.status === 409);
  check('Perdedor recebe conflito de versão explícito', /versão do catálogo mudou/i.test(rejected.body.message));
  const receipt = success.body.data;
  const winningPayload = commands[success.index];
  const replay = await context.request.post(base + endpoint, { data: winningPayload, headers });
  const again = (await replay.json()).data;
  check('Reenvio após concorrência conserva o único evento vencedor', replay.status() === 200 && again.reenvio === true && again.eventoId === receipt.eventoId && again.versaoAtual === receipt.versaoAtual);
  const reused = await context.request.post(base + endpoint, { data: { ...winningPayload, motivo: 'SINTETICO E2E — outra intenção usando chave indevida' }, headers });
  check('Reutilizar chave com outra intenção é conflito', reused.status() === 409);
  const final = await read(itemUrl);
  check('Versão persistida corresponde ao recibo vencedor', final.version === receipt.versaoAtual && final.ativo === winningPayload.ativo);
  recordBusiness({ concorrenciaCatalogoEventoId: receipt.eventoId, concorrenciaCatalogoVersao: receipt.versaoAtual, concorrenciaCatalogoReplay: winningPayload, concorrenciaCatalogoAtivo: final.ativo, catalogoConhecidoAntesConcorrencia: beforeConcurrent });
  report.controls = { anonymous: unauthenticated.status(), csrf: noCsrf.status(), origin: badOrigin.status(), password: wrongPassword.status(), reusedKey: reused.status(), persistence: { source: 'recibo do supervisor e respostas HTTP deste cenário', mysqlVersion: runtimeObservation.mysql.version, serverUuid: runtimeObservation.mysql.serverUuid, schema: runtimeObservation.mysql.schema, port: runtimeObservation.mysql.port, jarSha256: runtimeObservation.java.jarSha256, receiptSha256: runtimeObservation.receiptSha256, directDatabaseWrites: false } };
});
