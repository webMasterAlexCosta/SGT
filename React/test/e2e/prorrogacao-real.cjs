// Auxiliar E2E-04: UI real → prévia → senha → JAR → GET/histórico.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { baseFrontend, contratoDaFixture } = require('./contexto-fixture.cjs');
const { execute } = require('./ambiente-real.cjs');
const hash = value => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');

execute('prorrogacao-real', async ({ page, context, fixture, report, check, open, confirmPassword, recordBusiness, screenshot }) => {
  const business = JSON.parse(fs.readFileSync(path.join(process.env.SGT_TEST_RUNTIME, 'private/e2e-business.json')));
  check('Prorrogação desta intenção ainda não foi executada', !business.prorrogacaoFinal02Id);
  const contract = contratoDaFixture(fixture);
  const base = baseFrontend();
  await open('/contratos');
  const get = async route => {
    const response = await context.request.get(base + route);
    check(`GET independente ${route}`, response.status() === 200);
    return (await response.json()).data;
  };
  const before = await get(contract.api);
  const previousVersions = await get(contract.api + '/versoes');
  const previousActs = await get(contract.api + '/aditamentos');
  const identification = 'SINTETICO-E2E-PRORROGACAO-FINAL02';
  check('Publicado com fim conhecido e sem duplicar ato anterior', before.estadoNegocial === 'PUBLICADO' && /^\d{4}-\d{2}-\d{2}$/.test(before.dataFim) && !previousActs.some(item => item.identificacao === identification));
  const end = new Date(before.dataFim + 'T12:00:00Z');
  end.setUTCDate(end.getUTCDate() + 7);
  const newEnd = end.toISOString().slice(0, 10);
  report.scope = 'E2E04_PRORROGACAO_NOT_AN_ADDITIONAL_ORIGINAL_DRIVER';
  report.dates = { effective: fixture.dates.today, previousEnd: before.dataFim, newEnd };
  await page.getByRole('button', { name: contract.botaoAbrir, exact: true }).click();
  const detail = page.getByRole('dialog', { name: contract.titulo, exact: true });
  await detail.getByRole('tab', { name: 'Aditamentos', exact: true }).click();
  const form = detail.getByRole('heading', { name: 'Novo aditamento', exact: true }).locator('..');
  const field = form.getByLabel('Nova data final da vigência', { exact: true });
  check('Campo novaDataFim existe e é editável no formulário real', await field.isVisible() && await field.isEditable());
  await form.getByLabel(/^Identificação/).fill(identification);
  await form.getByLabel(/^Data efetiva/).fill(fixture.dates.today);
  await form.getByLabel('Data do documento', { exact: true }).fill(fixture.dates.today);
  await form.getByLabel('Data da assinatura', { exact: true }).fill(fixture.dates.today);
  await field.fill(newEnd);
  await form.getByLabel('Referência SEI', { exact: true }).fill('SINTETICO-E2E-PRORROGACAO-SEM-VALIDADE-REAL');
  await form.getByLabel(/^Justificativa/).fill('SINTETICO E2E: prorrogação contínua de sete dias, sem alterar capacidade, empresa, jornada ou identidade.');
  check('Confirmação indisponível antes da prévia', await form.getByRole('button', { name: 'Confirmar com esta prévia', exact: true }).isDisabled());
  const endpoint = contract.api + '/aditamentos';
  const previewPending = page.waitForResponse(r => new URL(r.url()).pathname === endpoint + '/previa' && r.request().method() === 'POST');
  previewPending.catch(() => {});
  await form.getByRole('button', { name: 'Calcular prévia', exact: true }).click();
  const previewResponse = await previewPending;
  const previewEnvelope = await previewResponse.json();
  check('Prévia Java200 contém a novaDataFim preenchida pelo React', previewResponse.status() === 200 && previewResponse.request().postDataJSON().novaDataFim === newEnd, { status: previewResponse.status(), code: previewEnvelope.code });
  const preview = previewEnvelope.data;
  check('Prorrogação mantém capacidade e não usa redução excepcional', preview.efetivoAnterior === before.efetivoPrevisto && preview.efetivoResultante === before.efetivoPrevisto && preview.exigeAutorizacaoExcepcional === false);
  await form.getByRole('heading', { name: 'Prévia calculada no servidor', exact: true }).waitFor();
  const impact = form.getByLabel('Confirmo que revisei o impacto de ocupação. Nenhuma pessoa será movida automaticamente.', { exact: true });
  if (await impact.isVisible()) await impact.check();
  await screenshot('novaDataFim-previa');
  const confirmed = page.waitForResponse(r => new URL(r.url()).pathname === endpoint && r.request().method() === 'POST');
  confirmed.catch(() => {});
  await form.getByRole('button', { name: 'Confirmar com esta prévia', exact: true }).click();
  await confirmPassword();
  const response = await confirmed;
  const envelope = await response.json();
  check('Prorrogação confirmada com senha pelo Java201', response.status() === 201, { status: response.status(), code: envelope.code, message: envelope.message });
  const receipt = envelope.data;
  recordBusiness({ prorrogacaoFinal02Id: receipt.id, prorrogacaoFinal02EventoId: receipt.eventoId, prorrogacaoFinal02FimAnterior: before.dataFim, prorrogacaoFinal02NovoFim: newEnd, prorrogacaoFinal02Payload: response.request().postDataJSON() });
  check('Primeiro recibo informa o fim solicitado e o mesmo contrato', receipt.contratoId === contract.id && receipt.novaDataFim === newEnd && receipt.identificacao === identification && receipt.eventoId > 0);
  const after = await get(contract.api);
  const acts = await get(endpoint);
  const versions = await get(contract.api + '/versoes');
  const events = await get(contract.api + '/eventos');
  check('GET corrente confirma novo fim com capacidade e empresa preservadas', after.dataFim === newEnd && after.efetivoPrevisto === before.efetivoPrevisto && after.fornecedorId === before.fornecedorId);
  check('Histórico real contém o aditamento e seu evento', acts.filter(item => item.id === receipt.id && item.novaDataFim === newEnd).length === 1 && events.some(item => item.id === receipt.eventoId && item.tipoEvento === 'ADITAMENTO'));
  check('Nova fotografia persistida sem reescrever nenhuma anterior', versions.length === previousVersions.length + 1 && previousVersions.every(old => hash(versions.find(item => item.id === old.id)) === hash(old)));
  report.receipt = { id: receipt.id, event: receipt.eventoId, versionsBefore: previousVersions.length, versionsAfter: versions.length };
  await detail.getByText(new RegExp(identification.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))).waitFor();
  await screenshot('prorrogacao-historico');
});
