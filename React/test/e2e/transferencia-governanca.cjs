const { baseFrontend, contratoDaFixture } = require('./contexto-fixture.cjs');
const fs = require('node:fs');
const path = require('node:path');
const { execute } = require('./ambiente-real.cjs');
execute('transferencia-governanca', async ({ page, context, fixture, check, screenshot, open, confirmPassword, recordBusiness, report }) => {
  const contratoAlvo = contratoDaFixture(fixture);
  const runtime = process.env.SGT_TEST_RUNTIME;
  const business = JSON.parse(fs.readFileSync(path.join(runtime, 'private/e2e-business.json')));
  check('Concessão real anterior existe na fixture de navegador', !!business.permissaoTransferenciaId);
  const base = baseFrontend();
  const admin = await context.browser().newContext({ storageState: path.join(runtime, 'private/e2e-fixture_admin-browser-state.json') });
  const apiGet = async route => (await (await context.request.get(base + '/api' + route)).json()).data;
  const adminPost = async (route, data) => {
    const csrfResponse = await admin.request.get(base + '/api/autenticacao/csrf');
    const csrf = (await csrfResponse.json()).data;
    const response = await admin.request.post(base + '/api' + route, { data, headers: { [csrf.headerName]: csrf.token, 'X-User-Password': fixture.accounts.fixture_admin.password, Origin: base } });
    report.http.push({ method: 'POST', path: '/api' + route, status: response.status(), driver: 'APIRequestContext — administrador em sessão independente' });
    check(`Ação administrativa real ${route}`, response.ok(), { status: response.status() });
    return (await response.json()).data;
  };
  const grant = (await (await admin.request.get(base + '/api/permissoes-excepcionais')).json()).data.find(item => item.id === business.permissaoTransferenciaId);
  check('Concessão corrente está ativa e fornece referência administrativa', grant?.ativa === true && !!grant.autorizacaoAdministrativa);
  await open('/contratos');
  await page.getByRole('button', { name: contratoAlvo.botaoAbrir, exact: true }).click();
  const detail = page.getByRole('dialog', { name: contratoAlvo.titulo, exact: true });
  await detail.getByRole('tab', { name: 'Transferências', exact: true }).click();
  const form = detail.getByRole('form', { name: 'Transferência de gestão', exact: true });
  const motivo = 'SINTETICO E2E — transferência futura com vínculo preservado';
  await form.getByLabel(/Data efetiva da transferência/).fill(fixture.dates.future);
  await form.getByLabel('Data do ato de transferência', { exact: true }).fill(fixture.dates.today);
  await form.getByLabel('Gestão destino (ID)', { exact: true }).fill(String(fixture.ids.gestao_destino));
  await form.getByLabel('Tipo de contratação destino (ID)', { exact: true }).fill(String(fixture.ids.destino_tipo));
  await form.getByLabel(/SEI da transferência/).fill('SINTETICO-E2E-TRANSFERENCIA-FUTURA');
  await form.getByLabel(/Autorização administrativa/).fill(grant.autorizacaoAdministrativa);
  await form.getByLabel(/Motivo da transferência/).fill(motivo);
  await form.getByRole('button', { name: 'Adicionar mapa', exact: true }).click();
  const mapping = { 'Composição origem': fixture.ids.composicao_contrato_rascunho, 'Lotação origem': fixture.ids.lotacao, 'Turno origem': fixture.ids.jornada, 'Cargo origem': fixture.ids.cargo, 'Lotação destino': fixture.ids.destino_lotacao, 'Turno destino': fixture.ids.destino_jornada, 'Cargo destino': fixture.ids.destino_cargo };
  for (const [label, id] of Object.entries(mapping)) await form.getByLabel(`${label} do mapa 1`, { exact: true }).fill(String(id));
  const gerar = async () => {
    const preview = page.waitForResponse(r => new URL(r.url()).pathname === `${contratoAlvo.api}/transferencias-gestao/previa` && r.request().method() === 'POST');
    await form.getByRole('button', { name: 'Gerar prévia da transferência', exact: true }).click();
    const response = await preview;
    check('Prévia real da transferência aprovada', response.status() === 200, { status: response.status() });
    await form.getByLabel('Confirmo os impactos e os mapas desta transferência.', { exact: true }).check();
  };
  await gerar();
  await screenshot('previa-antes-revogacao');
  await adminPost(`/permissoes-excepcionais/${grant.id}/revogar`, { motivo: 'SINTETICO E2E — revogação entre prévia e confirmação.' });
  const rejected = page.waitForResponse(r => new URL(r.url()).pathname === `${contratoAlvo.api}/transferir-gestao` && r.request().method() === 'POST');
  await form.getByRole('button', { name: 'Confirmar transferência', exact: true }).click();
  await confirmPassword();
  check('Revogação posterior à prévia bloqueia a confirmação no Java', (await rejected).status() === 403);
  await detail.getByRole('alert').filter({ hasText: /concessão|autoriz|permiss/i }).waitFor();
  check('Falha de autorização preserva o formulário e exige nova prévia', await form.getByLabel(/Motivo da transferência/).inputValue() === motivo && await form.getByRole('button', { name: 'Confirmar transferência', exact: true }).isDisabled());
  check('Tentativa revogada não persistiu transferência', (await apiGet(`${contratoAlvo.caminho}/transferencias-gestao`)).length === 0);
  await screenshot('autorizacao-revogada');
  const renewed = await adminPost('/permissoes-excepcionais', {
    tipo: grant.tipo, usuarioBeneficiarioId: grant.usuarioBeneficiarioId, contratoId: grant.contratoId, gestaoLocalId: grant.gestaoLocalId,
    finalidade: grant.finalidade, justificativa: 'SINTETICO E2E — nova concessão após bloqueio comprovado.',
    autorizacaoAdministrativa: 'SINTETICO-E2E-RECONCESSAO', validoAte: new Date(Date.now() + 86400000).toISOString(),
  });
  recordBusiness({ permissaoTransferenciaId: renewed.id, permissaoTransferenciaRevogadaId: grant.id });
  await form.getByLabel(/Autorização administrativa/).fill(renewed.autorizacaoAdministrativa);
  const confirmar = async () => {
    const result = page.waitForResponse(r => new URL(r.url()).pathname === `${contratoAlvo.api}/transferir-gestao` && r.request().method() === 'POST');
    await form.getByRole('button', { name: 'Confirmar transferência', exact: true }).click();
    await confirmPassword();
    check('Transferência confirmada pelo Java após nova prévia', (await result).status() === 200);
    await form.getByRole('button', { name: 'Gerar prévia da transferência', exact: true }).waitFor();
  };
  await gerar();
  await confirmar();
  let transfers = await apiGet(`${contratoAlvo.caminho}/transferencias-gestao`);
  const first = transfers.find(item => item.motivo === motivo);
  check('Ato preserva origem, destino, tipo e mapas', first?.gestaoOrigemId === fixture.ids.gestao_origem && first.gestaoDestinoId === fixture.ids.gestao_destino && first.tipoContratacaoDestinoId === fixture.ids.destino_tipo && first.mapeamentos.length === 1);
  recordBusiness({ transferenciaInicialId: first.id, transferenciaEventoInicialId: first.eventoContratoId });
  const future = await apiGet(`${contratoAlvo.caminho}/posicao-temporal?data=${fixture.dates.future}`);
  const today = await apiGet(`${contratoAlvo.caminho}`);
  const vinculo = await apiGet(`/vinculos-contratuais/${business.vinculoId}`);
  check('Transferência futura não muda a custódia atual', today.gestaoLocalId === fixture.ids.gestao_origem && future.versaoContratual.gestaoLocalId === fixture.ids.gestao_destino);
  check('Mesmo Vínculo e mesma Pessoa após transferência programada', vinculo.id === business.vinculoId && vinculo.pessoaId === business.pessoaId);
  const card = detail.locator('article').filter({ hasText: motivo }).first();
  await card.getByRole('button', { name: 'Retificar transferência', exact: true }).click();
  check('Retificação conserva origem e referência ao ato anterior', await form.getByLabel('Composição origem do mapa 1', { exact: true }).inputValue() === String(fixture.ids.composicao_contrato_rascunho) && await form.getByLabel('Evento precedente da transferência (ID)', { exact: true }).inputValue() === String(first.eventoContratoId));
  const motivoRetificado = 'SINTETICO E2E — retificação documental da transferência futura';
  await form.getByLabel(/Motivo da transferência/).fill(motivoRetificado);
  await form.getByLabel(/SEI da transferência/).fill('SINTETICO-E2E-TRANSFERENCIA-RETIFICADA');
  await form.getByLabel(/Autorização administrativa/).fill('SINTETICO-E2E-RECONCESSAO');
  await gerar();
  await confirmar();
  transfers = await apiGet(`${contratoAlvo.caminho}/transferencias-gestao`);
  const revised = transfers.find(item => item.motivo === motivoRetificado);
  check('Retificação gera ato próprio e preserva o ato original', revised?.id !== first.id && transfers.some(item => item.id === first.id));
  recordBusiness({ transferenciaRetificadaId: revised.id, transferenciaEventoRetificadoId: revised.eventoContratoId });
  await screenshot('transferencia-retificada');
  const latest = detail.locator('article').filter({ hasText: motivoRetificado }).first();
  await latest.getByRole('button', { name: 'Cancelar transferência futura', exact: true }).click();
  const cancellation = detail.getByRole('form', { name: 'Cancelamento de transferência', exact: true });
  await cancellation.getByLabel(/SEI do cancelamento/).fill('SINTETICO-E2E-CANCELAMENTO-FUTURO');
  await cancellation.getByLabel(/Autorização do cancelamento/).fill('SINTETICO-E2E-RECONCESSAO');
  await cancellation.getByLabel(/Motivo do cancelamento/).fill('SINTETICO E2E — cancelar efeito futuro e manter a cadeia íntegra.');
  const cancelResponse = page.waitForResponse(r => new URL(r.url()).pathname === `${contratoAlvo.api}/transferencias-gestao/${revised.id}/cancelar` && r.request().method() === 'POST');
  await cancellation.getByRole('button', { name: 'Confirmar cancelamento', exact: true }).click();
  await confirmPassword();
  check('Cancelamento futuro confirmado no Java', (await cancelResponse).status() === 200);
  const futureAfter = await apiGet(`${contratoAlvo.caminho}/posicao-temporal?data=${fixture.dates.future}`);
  check('Cancelamento retira o efeito futuro sem apagar o histórico', futureAfter.versaoContratual.gestaoLocalId === fixture.ids.gestao_origem && (await apiGet(`${contratoAlvo.caminho}/transferencias-gestao`)).length === transfers.length);
  recordBusiness({ transferenciaFuturaCancelada: true });
  await screenshot('cancelamento-preservado');
  await admin.close();
});
