const { baseFrontend, contratoDaFixture } = require('./contexto-fixture.cjs');
const crypto = require('node:crypto');
const { execute } = require('./ambiente-real.cjs');
const hash = value => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');
execute('historico-contrato', async ({ page, context, account, fixture, check, screenshot, open, confirmPassword, recordBusiness, report }) => {
  const contratoAlvo = contratoDaFixture(fixture);
  await open('/historico');
  const base = baseFrontend();
  const endpoint = `${contratoAlvo.api}/provas-historicas`;
  const get = async (route, params) => {
    const response = await context.request.get(base + '/api' + route, { params });
    check(`Consulta real ${route}`, response.ok(), { status: response.status() });
    return (await response.json()).data;
  };
  const events = await get(`${contratoAlvo.caminho}/eventos`);
  const versions = await get(`${contratoAlvo.caminho}/versoes`);
  const origin = events.find(event => event.tipoEvento === 'PUBLICACAO');
  const original = versions.find(version => version.eventoOrigemId === origin?.id);
  const existingProofs = await get(`${contratoAlvo.caminho}/provas-historicas`);
  const precedingProof = existingProofs.filter(proof => proof.eventoOrigemId === origin?.id).sort((a, b) => b.numeroRevisao - a.numeroRevisao)[0];
  const precedingVersionId = precedingProof?.versaoGeradaId || original?.id;
  check('Publicação e fotografia originais existem no Java', !!origin?.id && !!original?.id);
  const originalSha = hash(original);
  const before = new Date().toISOString();
  const positionBefore = await get(`${contratoAlvo.caminho}/posicao-temporal`, { data: fixture.dates.today, conhecidoAte: before });
  const query = page.getByRole('form', { name: 'Consulta histórica' });
  await query.getByLabel('ID do contrato', { exact: true }).fill(String(contratoAlvo.id));
  await query.getByLabel('Data efetiva consultada', { exact: true }).fill(fixture.dates.today);
  await query.getByLabel('Conhecido até (ISO com fuso)', { exact: true }).fill(before);
  await query.getByRole('button', { name: 'Consultar histórico', exact: true }).click();
  await page.locator('summary').filter({ hasText: 'Publicação original e acervo contratual' }).click();
  await page.getByRole('heading', { name: 'Publicação original: eventos preservados', exact: true }).waitFor();
  check('Interface exibe a publicação fornecida pelo servidor', await page.getByRole('heading', { name: 'Fotografias vinculadas à publicação', exact: true }).isVisible());
  await screenshot('publicacao-original');
  await page.locator('summary').filter({ hasText: 'Incorporar uma fonte histórica' }).click();
  const form = page.getByRole('form', { name: 'Fonte histórica' });
  await form.getByRole('button', { name: 'Carregar versões atuais', exact: true }).click();
  const versionId = await form.getByLabel('Versão esperada do contrato', { exact: true }).getAttribute('id');
  await page.waitForFunction(id => document.getElementById(id)?.value !== '', versionId);
  await form.getByLabel('Data do documento original', { exact: true }).fill(fixture.dates.today);
  await form.getByLabel('ID do evento de origem', { exact: true }).fill(String(origin.id));
  await form.getByLabel('ID da fotografia anterior', { exact: true }).fill(String(precedingVersionId));
  if (precedingProof) await form.getByLabel('ID da prova anterior', { exact: true }).fill(String(precedingProof.id));
  await form.getByLabel('Referência SEI', { exact: true }).fill('SINTETICO-E2E-FONTE-CONTRATO-20261101');
  await form.getByLabel('Motivo / justificativa', { exact: true }).fill('Fonte sintética complementar para testar imutabilidade da publicação, sem validade administrativa.');
  await form.getByLabel('Autorização', { exact: true }).fill('SINTETICO-E2E-CONCESSAO-VIGENTE');
  await form.locator('summary').filter({ hasText: 'Fotografia documentada' }).click();
  await form.getByLabel('Comprovado: Descrição documentada do contrato', { exact: true }).check();
  const description = form.getByLabel('Descrição documentada do contrato', { exact: true });
  const contradicao = original.descricao + ' — CONTRADICAO SINTETICA';
  await description.fill(contradicao);
  const rejected = page.waitForResponse(r => new URL(r.url()).pathname === endpoint + '/previa' && r.request().method() === 'POST');
  await form.getByRole('button', { name: 'Gerar prévia', exact: true }).click();
  check('Java rejeita fonte tardia que contradiz a publicação', (await rejected).status() === 409);
  await form.getByRole('alert').filter({ hasText: 'contradiz' }).waitFor();
  check('Interface mantém conteúdo rejeitado e impede confirmação', await description.inputValue() === contradicao && await form.getByRole('button', { name: 'Confirmar incorporação', exact: true }).isDisabled());
  await screenshot('contradicao-rejeitada');
  await description.fill(original.descricao);
  const previewed = page.waitForResponse(r => new URL(r.url()).pathname === endpoint + '/previa' && r.status() === 200);
  await form.getByRole('button', { name: 'Gerar prévia', exact: true }).click();
  const previewResponse = await previewed;
  const previewPayload = previewResponse.request().postDataJSON();
  const csrf = (await (await context.request.get(base + '/api/autenticacao/csrf')).json()).data;
  const headers = { [csrf.headerName]: csrf.token, 'X-User-Password': account.password, Origin: base };
  const invalid = await context.request.post(base + endpoint, { data: { ...previewPayload, confirmarImpacto: true, tokenPrevia: 'SINTETICO-TOKEN-INVALIDO' }, headers });
  check('Java recusa token inválido sem criar prova', invalid.status() === 409);
  report.http.push({ method: 'POST', path: endpoint, status: invalid.status(), driver: 'APIRequestContext — token deliberadamente inválido' });
  await form.getByLabel('Li os impactos e confirmo esta intenção.', { exact: true }).check();
  const confirmed = page.waitForResponse(r => new URL(r.url()).pathname === endpoint && r.request().method() === 'POST' && r.status() === 201, { timeout: 20000 });
  await form.getByRole('button', { name: 'Confirmar incorporação', exact: true }).click();
  await confirmPassword();
  const response = await confirmed;
  const receipt = (await response.json()).data;
  const payload = response.request().postDataJSON();
  recordBusiness({ contratoProvaId: receipt.id, contratoReplay: payload, contratoEndpoint: endpoint, contratoConhecidoAntes: before, contratoPublicacaoId: origin.id, contratoVersaoOriginalId: original.id, contratoVersaoOriginalSha256: originalSha });
  check('Prova parcial registra vínculo explícito com a publicação e a fotografia anterior', receipt.eventoOrigemId === origin.id && receipt.versaoAnteriorId === precedingVersionId && receipt.configuracaoCompletaComprovada === false);
  const replay = await context.request.post(base + endpoint, { data: payload, headers });
  const again = (await replay.json()).data;
  check('Reenvio da mesma intenção mantém a prova e a fotografia gerada', replay.status() === 201 && again.id === receipt.id && again.versaoGeradaId === receipt.versaoGeradaId);
  report.http.push({ method: 'POST', path: endpoint, status: replay.status(), driver: 'APIRequestContext — reenvio da intenção capturada no React' });
  const versionsAfter = await get(`${contratoAlvo.caminho}/versoes`);
  check('Fotografia original permanece byte a byte igual na representação JSON', hash(versionsAfter.find(version => version.id === original.id)) === originalSha, { originalId: original.id, sha256: originalSha });
  const previous = await get(`${contratoAlvo.caminho}/posicao-temporal`, { data: fixture.dates.today, conhecidoAte: before });
  const current = await get(`${contratoAlvo.caminho}/posicao-temporal`, { data: fixture.dates.today });
  // O replay negocial Java retorna uma projeção com id=null (AditamentoContratualServico).
  // Compare os valores efetivamente retornados e os recibos conhecidos em cada corte.
  check('Corte anterior mantém integralmente a posição que o Java já retornava', hash(previous.versaoContratual) === hash(positionBefore.versaoContratual));
  const proofsBefore = await get(`${contratoAlvo.caminho}/provas-historicas`, { conhecidoAte: before });
  const proofsNow = await get(`${contratoAlvo.caminho}/provas-historicas`);
  check('Cortes de conhecimento distinguem a nova prova preservada', !proofsBefore.some(proof => proof.id === receipt.id) && proofsNow.some(proof => proof.id === receipt.id));
  check('Conhecimento atual conserva os valores documentados da publicação', current.versaoContratual.eventoOrigemId === origin.id && current.versaoContratual.descricao === original.descricao);
  await screenshot('prova-registrada');
  await query.getByLabel('ID do contrato', { exact: true }).fill(String(contratoDaFixture(fixture, 'contrato_futuro').id));
  await query.getByLabel('Data efetiva consultada', { exact: true }).fill(fixture.dates.future);
  await query.getByLabel('Conhecido até (ISO com fuso)', { exact: true }).fill('');
  await query.getByRole('button', { name: 'Consultar histórico', exact: true }).click();
  await page.locator('summary').filter({ hasText: 'Publicação original e acervo contratual' }).click();
  await page.getByText(/Publicação original não comprovada no acervo retornado/).waitFor();
  check('Rascunho nunca publicado não recebe publicação fictícia na interface', await page.getByRole('heading', { name: 'Publicação original: eventos preservados', exact: true }).count() === 0);
  await screenshot('rascunho-sem-publicacao');
});
