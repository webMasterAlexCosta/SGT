const { baseFrontend } = require('./contexto-fixture.cjs');
const { execute } = require('./ambiente-real.cjs');
execute('historico-catalogo', async ({ page, context, account, fixture, check, screenshot, open, confirmPassword, recordBusiness, report }) => {
  await open('/historico');
  await page.getByRole('tab', { name: 'Catálogo', exact: true }).click();
  const query = page.getByRole('form', { name: 'Consulta histórica' });
  await query.getByLabel(/Tipo de catálogo/).selectOption('MOTIVO_DESLIGAMENTO');
  await query.getByLabel('ID do item do catálogo', { exact: true }).fill(String(fixture.ids.motivo_desligamento));
  await query.getByLabel('Data efetiva consultada', { exact: true }).fill(fixture.dates.today);
  const before = new Date().toISOString();
  await query.getByLabel('Conhecido até (ISO com fuso)', { exact: true }).fill(before);
  await query.getByRole('button', { name: 'Consultar histórico', exact: true }).click();
  const details = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: 'Registrar um ato de disponibilidade' }) }).first();
  await details.locator('summary').first().click();
  const form = page.getByRole('form', { name: 'Fonte histórica' });
  await form.getByRole('button', { name: 'Carregar versões atuais', exact: true }).click();
  const versaoId = await form.getByLabel('Versão esperada do catálogo', { exact: true }).getAttribute('id');
  await page.waitForFunction(id => document.getElementById(id)?.value !== '', versaoId);
  await form.getByLabel('Data efetiva da transição', { exact: true }).fill(fixture.dates.today);
  await form.getByLabel('Disponibilidade documentada', { exact: true }).selectOption('false');
  await form.getByLabel('Evidência da transição', { exact: true }).fill('SINTETICO-E2E-CAT-20261101 — sem validade administrativa.');
  await form.getByLabel('Motivo / justificativa', { exact: true }).fill('Inativação sintética para comprovar os dois cortes temporais.');
  await form.getByLabel('Autorização', { exact: true }).fill('SINTETICO-E2E-GESTOR-LOCAL');
  const endpoint = `/api/catalogos-temporais/MOTIVO_DESLIGAMENTO/${fixture.ids.motivo_desligamento}/transicoes`;
  await form.getByRole('button', { name: 'Gerar prévia', exact: true }).click();
  await form.getByRole('heading', { name: 'Impactos informados pelo servidor' }).waitFor();
  check('Aceite explícito é obrigatório após a prévia', await form.getByRole('button', { name: 'Registrar transição', exact: true }).isDisabled());
  await form.getByLabel('Li os impactos e confirmo esta intenção.', { exact: true }).check();
  await screenshot('previa');
  const confirmed = page.waitForResponse(r => new URL(r.url()).pathname === endpoint && r.request().method() === 'POST' && r.status() < 300, { timeout: 20000 });
  await form.getByRole('button', { name: 'Registrar transição', exact: true }).click();
  await confirmPassword();
  const response = await confirmed;
  const receipt = (await response.json()).data;
  const payload = response.request().postDataJSON();
  recordBusiness({ catalogoEventoId: receipt.eventoId, catalogoReplay: payload, catalogoEndpoint: endpoint, catalogoConhecidoAntes: before });
  check('Transição real persistida com versão e evento', receipt.ativo === false && receipt.eventoId > 0 && receipt.reenvio === false, { status: response.status(), eventoId: receipt.eventoId, versaoAtual: receipt.versaoAtual });
  await form.getByText('Registrado com sucesso no servidor.', { exact: true }).waitFor();
  const base = baseFrontend();
  const csrf = (await (await context.request.get(base + '/api/autenticacao/csrf')).json()).data;
  const replay = await context.request.post(base + endpoint, { data: payload, headers: { [csrf.headerName]: csrf.token, 'X-User-Password': account.password, Origin: base } });
  const again = (await replay.json()).data;
  report.http.push({ method: 'POST', path: endpoint, status: replay.status(), driver: 'APIRequestContext — reenvio do comando capturado no React' });
  check('Reenvio idempotente retorna o mesmo evento', replay.ok() && again.reenvio === true && again.eventoId === receipt.eventoId && again.versaoAtual === receipt.versaoAtual, { eventoId: again.eventoId, reenvio: again.reenvio });
  const availability = endpoint.replace('/transicoes', '/disponibilidade');
  const previous = (await (await context.request.get(base + availability, { params: { data: fixture.dates.today, conhecidoAte: before } })).json()).data;
  const current = (await (await context.request.get(base + availability, { params: { data: fixture.dates.today } })).json()).data;
  check('Corte anterior mantém estado documentado ativo', previous.disponibilidadeComprovada === true && previous.ativo === true);
  check('Conhecimento atual retorna estado documentado inativo', current.disponibilidadeComprovada === true && current.ativo === false);
  await screenshot('registrado');
});
