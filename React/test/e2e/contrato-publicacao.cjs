const { baseFrontend, contratoDaFixture } = require('./contexto-fixture.cjs');
const { execute } = require('./ambiente-real.cjs');
execute('contrato-publicacao', async ({ page, context, fixture, check, screenshot, open, confirmPassword, report }) => {
  const contratoAlvo = contratoDaFixture(fixture);
  await open('/contratos');
  await page.getByRole('heading', { name: 'Contratos de terceirização' }).waitFor();
  check('Sessão e listagem reais disponíveis', page.url().endsWith('/contratos'));
  await screenshot('listagem');
  await page.getByRole('button', { name: contratoAlvo.botaoAbrir, exact: true }).click();
  const detail = page.getByRole('dialog', { name: contratoAlvo.titulo, exact: true });
  await detail.waitFor();
  await detail.getByRole('button', { name: 'Publicar', exact: true }).click();
  const modal = page.getByRole('dialog', { name: 'Publicar contrato', exact: true });
  await modal.getByLabel(/Data da publicação/).fill(fixture.dates.today);
  await modal.getByLabel(/Referência SEI/).fill('SINTETICO-E2E-PUBLICACAO-20261101');
  await modal.getByLabel(/Justificativa/).fill('Publicação sintética de homologação pela interface React.');
  check('Confirmação bloqueada antes da prévia', await modal.getByRole('button', { name: /Continuar e confirmar senha/ }).isDisabled());
  await modal.getByRole('button', { name: 'Gerar prévia', exact: true }).click();
  await modal.getByRole('heading', { name: 'Prévia de impactos' }).waitFor();
  await screenshot('previa');
  await modal.getByLabel(/Confirmo os impactos/).check();
  await modal.getByRole('button', { name: /Continuar e confirmar senha/ }).click();
  await confirmPassword();
  await modal.waitFor({ state: 'hidden', timeout: 15000 });
  const response = await context.request.get(baseFrontend() + contratoAlvo.api);
  const envelope = await response.json();
  check('Publicação persistida retornada pelo Java', response.status() === 200 && envelope.data.estadoNegocial === 'PUBLICADO', { status: response.status(), estado: envelope.data?.estadoNegocial, version: envelope.data?.version });
  check('Prévia executada via HTTP real', report.http.some(r => r.method === 'POST' && /previa/.test(r.path) && r.status === 200));
  check('Confirmação executada via HTTP real', report.http.some(r => r.method === 'POST' && /publicar$/.test(r.path) && r.status < 300));
  await screenshot('publicado');
});
